#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn marching_cubes_tables_are_consistent() {
        for case in 0..256 {
            let mask = EDGE_TABLE[case];
            let row = &TRI_TABLE[case];
            let mut len = 0usize;
            let mut used_mask = 0u16;
            while len < 16 && row[len] != -1 {
                let e = row[len];
                assert!((0..12).contains(&e), "invalid edge {e} in case {case}");
                used_mask |= 1 << (e as u16);
                len += 1;
            }
            assert_eq!(len % 3, 0, "non-triangle count in case {case}");
            assert_eq!(
                used_mask, mask,
                "edge mask mismatch in case {case}: used {used_mask:#x} vs table {mask:#x}"
            );
        }
    }
}
