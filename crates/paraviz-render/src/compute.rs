//! WebGPU Compute Marching Cubes engine (`GpuContourEngine`) extracting watertight
//! isosurfaces directly on the GPU from [`ImageData`] scalar grids into [`PolyData`].

use crate::renderer::RenderError;
use bytemuck::{Pod, Zeroable};
use paraviz_core::{DataArray, ImageData, PolyData};
use std::collections::HashMap;
use std::sync::Arc;
use wgpu::util::DeviceExt;

#[repr(C)]
#[derive(Debug, Clone, Copy, Pod, Zeroable)]
struct McUniforms {
    dims: [u32; 4],
    origin: [f32; 4],
    spacing: [f32; 4],
    max_triangles: u32,
    _pad0: u32,
    _pad1: u32,
    _pad2: u32,
}

#[repr(C)]
#[derive(Debug, Clone, Copy, Pod, Zeroable)]
struct GpuMcVertex {
    pos_scalar: [f32; 4],
    normal_t: [f32; 4],
    edge_key: [u32; 4],
}

const MC_COMPUTE_WGSL: &str = r#"
struct McUniforms {
    dims: vec4<u32>,
    origin: vec4<f32>,
    spacing: vec4<f32>,
    max_triangles: u32,
    _pad0: u32,
    _pad1: u32,
    _pad2: u32,
};

struct GpuMcVertex {
    pos_scalar: vec4<f32>,
    normal_t: vec4<f32>,
    edge_key: vec4<u32>,
};

@group(0) @binding(0)
var<uniform> u: McUniforms;
@group(0) @binding(1)
var<storage, read> scalars: array<f32>;
@group(0) @binding(2)
var<storage, read> edge_table: array<u32>;
@group(0) @binding(3)
var<storage, read> tri_table: array<i32>;
@group(0) @binding(4)
var<storage, read_write> counter: atomic<u32>;
@group(0) @binding(5)
var<storage, read_write> out_verts: array<GpuMcVertex>;

fn pt_index(i: u32, j: u32, k: u32) -> u32 {
    return i + u.dims.x * (j + u.dims.y * k);
}

fn pt_coords(i: u32, j: u32, k: u32) -> vec3<f32> {
    return u.origin.xyz + vec3<f32>(f32(i), f32(j), f32(k)) * u.spacing.xyz;
}

fn sample_grad_normal(i: u32, j: u32, k: u32) -> vec3<f32> {
    let nx = u.dims.x;
    let ny = u.dims.y;
    let nz = u.dims.z;

    let ix0 = select(i - 1u, 0u, i == 0u);
    let ix1 = min(i + 1u, nx - 1u);
    let iy0 = select(j - 1u, 0u, j == 0u);
    let iy1 = min(j + 1u, ny - 1u);
    let iz0 = select(k - 1u, 0u, k == 0u);
    let iz1 = min(k + 1u, nz - 1u);

    let dx_denom = max(f32(ix1 - ix0) * u.spacing.x, 1e-6);
    let dy_denom = max(f32(iy1 - iy0) * u.spacing.y, 1e-6);
    let dz_denom = max(f32(iz1 - iz0) * u.spacing.z, 1e-6);

    let gx = (scalars[pt_index(ix1, j, k)] - scalars[pt_index(ix0, j, k)]) / dx_denom;
    let gy = (scalars[pt_index(i, iy1, k)] - scalars[pt_index(i, iy0, k)]) / dy_denom;
    let gz = (scalars[pt_index(i, j, iz1)] - scalars[pt_index(i, j, iz0)]) / dz_denom;

    let g = vec3<f32>(gx, gy, gz);
    let len = length(g);
    if (len > 1e-8) {
        return g / len;
    }
    return vec3<f32>(0.0, 0.0, 1.0);
}

fn interp_edge_vertex(
    c_a_i: u32, c_a_j: u32, c_a_k: u32, va: f32,
    c_b_i: u32, c_b_j: u32, c_b_k: u32, vb: f32,
    iso: f32,
) -> GpuMcVertex {
    let ia = pt_index(c_a_i, c_a_j, c_a_k);
    let ib = pt_index(c_b_i, c_b_j, c_b_k);
    let denom = vb - va;
    var t: f32 = 0.5;
    if (abs(denom) > 1e-12) {
        t = clamp((iso - va) / denom, 0.0, 1.0);
    }
    let pa = pt_coords(c_a_i, c_a_j, c_a_k);
    let pb = pt_coords(c_b_i, c_b_j, c_b_k);
    let p = mix(pa, pb, t);
    let s = mix(va, vb, t);

    let na = sample_grad_normal(c_a_i, c_a_j, c_a_k);
    let nb = sample_grad_normal(c_b_i, c_b_j, c_b_k);
    let n_mix = mix(na, nb, t);
    let n_len = length(n_mix);
    let n = select(vec3<f32>(0.0, 0.0, 1.0), n_mix / n_len, n_len > 1e-8);

    let lo = min(ia, ib);
    let hi = max(ia, ib);

    var v: GpuMcVertex;
    v.pos_scalar = vec4<f32>(p, s);
    v.normal_t = vec4<f32>(n, t);
    v.edge_key = vec4<u32>(lo, hi, 0u, 0u);
    return v;
}

@compute @workgroup_size(4, 4, 4)
fn mc_main(@builtin(global_invocation_id) gid: vec3<u32>) {
    let cx = u.dims.x - 1u;
    let cy = u.dims.y - 1u;
    let cz = u.dims.z - 1u;
    if (gid.x >= cx || gid.y >= cy || gid.z >= cz) {
        return;
    }

    let i = gid.x;
    let j = gid.y;
    let k = gid.z;
    let iso = u.spacing.w;

    let ci = array<u32, 8>(i, i + 1u, i + 1u, i, i, i + 1u, i + 1u, i);
    let cj = array<u32, 8>(j, j, j + 1u, j + 1u, j, j, j + 1u, j + 1u);
    let ck = array<u32, 8>(k, k, k, k, k + 1u, k + 1u, k + 1u, k + 1u);

    var vals: array<f32, 8>;
    var cube_index: u32 = 0u;
    for (var b: u32 = 0u; b < 8u; b = b + 1u) {
        let v = scalars[pt_index(ci[b], cj[b], ck[b])];
        vals[b] = v;
        if (v < iso) {
            cube_index = cube_index | (1u << b);
        }
    }

    let edge_mask = edge_table[cube_index];
    if (edge_mask == 0u) {
        return;
    }

    var edge_c0 = array<u32, 12>(0u, 1u, 2u, 3u, 4u, 5u, 6u, 7u, 0u, 1u, 2u, 3u);
    var edge_c1 = array<u32, 12>(1u, 2u, 3u, 0u, 5u, 6u, 7u, 4u, 4u, 5u, 6u, 7u);

    var vert_list: array<GpuMcVertex, 12>;
    for (var e: u32 = 0u; e < 12u; e = e + 1u) {
        if ((edge_mask & (1u << e)) != 0u) {
            let a = edge_c0[e];
            let b = edge_c1[e];
            vert_list[e] = interp_edge_vertex(
                ci[a], cj[a], ck[a], vals[a],
                ci[b], cj[b], ck[b], vals[b],
                iso,
            );
        }
    }

    let base = cube_index * 16u;
    for (var t_off: u32 = 0u; t_off < 15u; t_off = t_off + 3u) {
        let e0 = tri_table[base + t_off];
        if (e0 < 0) {
            break;
        }
        let e1 = tri_table[base + t_off + 1u];
        let e2 = tri_table[base + t_off + 2u];
        let slot = atomicAdd(&counter, 1u);
        if (slot < u.max_triangles) {
            let out_base = slot * 3u;
            out_verts[out_base] = vert_list[u32(e0)];
            out_verts[out_base + 1u] = vert_list[u32(e1)];
            out_verts[out_base + 2u] = vert_list[u32(e2)];
        }
    }
}
"#;

/// GPU Marching Cubes contour engine using a WebGPU compute pipeline.
pub struct GpuContourEngine {
    device: Arc<wgpu::Device>,
    queue: Arc<wgpu::Queue>,
    bgl: wgpu::BindGroupLayout,
    pipeline: wgpu::ComputePipeline,
    edge_table_buf: wgpu::Buffer,
    tri_table_buf: wgpu::Buffer,
}

impl GpuContourEngine {
    /// Initializes a standalone headless [`GpuContourEngine`].
    pub fn new_headless() -> Result<Self, RenderError> {
        let instance = wgpu::Instance::new(wgpu::InstanceDescriptor::new_without_display_handle());
        let adapter = pollster::block_on(instance.request_adapter(&wgpu::RequestAdapterOptions {
            power_preference: wgpu::PowerPreference::HighPerformance,
            compatible_surface: None,
            force_fallback_adapter: false,
            apply_limit_buckets: false,
        }))
        .map_err(|_| RenderError::NoAdapter)?;

        let (device, queue) = pollster::block_on(adapter.request_device(&wgpu::DeviceDescriptor {
            label: Some("paraviz-compute-device"),
            required_features: wgpu::Features::empty(),
            required_limits: wgpu::Limits::default(),
            experimental_features: Default::default(),
            memory_hints: Default::default(),
            trace: Default::default(),
        }))?;

        Ok(Self::from_device(Arc::new(device), Arc::new(queue)))
    }

    /// Creates a [`GpuContourEngine`] sharing an existing WebGPU `Device` and `Queue`.
    pub fn from_device(device: Arc<wgpu::Device>, queue: Arc<wgpu::Queue>) -> Self {
        let shader = device.create_shader_module(wgpu::ShaderModuleDescriptor {
            label: Some("paraviz-mc-compute-shader"),
            source: wgpu::ShaderSource::Wgsl(MC_COMPUTE_WGSL.into()),
        });

        let bgl = device.create_bind_group_layout(&wgpu::BindGroupLayoutDescriptor {
            label: Some("paraviz-mc-bgl"),
            entries: &[
                wgpu::BindGroupLayoutEntry {
                    binding: 0,
                    visibility: wgpu::ShaderStages::COMPUTE,
                    ty: wgpu::BindingType::Buffer {
                        ty: wgpu::BufferBindingType::Uniform,
                        has_dynamic_offset: false,
                        min_binding_size: None,
                    },
                    count: None,
                },
                wgpu::BindGroupLayoutEntry {
                    binding: 1,
                    visibility: wgpu::ShaderStages::COMPUTE,
                    ty: wgpu::BindingType::Buffer {
                        ty: wgpu::BufferBindingType::Storage { read_only: true },
                        has_dynamic_offset: false,
                        min_binding_size: None,
                    },
                    count: None,
                },
                wgpu::BindGroupLayoutEntry {
                    binding: 2,
                    visibility: wgpu::ShaderStages::COMPUTE,
                    ty: wgpu::BindingType::Buffer {
                        ty: wgpu::BufferBindingType::Storage { read_only: true },
                        has_dynamic_offset: false,
                        min_binding_size: None,
                    },
                    count: None,
                },
                wgpu::BindGroupLayoutEntry {
                    binding: 3,
                    visibility: wgpu::ShaderStages::COMPUTE,
                    ty: wgpu::BindingType::Buffer {
                        ty: wgpu::BufferBindingType::Storage { read_only: true },
                        has_dynamic_offset: false,
                        min_binding_size: None,
                    },
                    count: None,
                },
                wgpu::BindGroupLayoutEntry {
                    binding: 4,
                    visibility: wgpu::ShaderStages::COMPUTE,
                    ty: wgpu::BindingType::Buffer {
                        ty: wgpu::BufferBindingType::Storage { read_only: false },
                        has_dynamic_offset: false,
                        min_binding_size: None,
                    },
                    count: None,
                },
                wgpu::BindGroupLayoutEntry {
                    binding: 5,
                    visibility: wgpu::ShaderStages::COMPUTE,
                    ty: wgpu::BindingType::Buffer {
                        ty: wgpu::BufferBindingType::Storage { read_only: false },
                        has_dynamic_offset: false,
                        min_binding_size: None,
                    },
                    count: None,
                },
            ],
        });

        let pipeline_layout = device.create_pipeline_layout(&wgpu::PipelineLayoutDescriptor {
            label: Some("paraviz-mc-pipeline-layout"),
            bind_group_layouts: &[Some(&bgl)],
            immediate_size: 0,
        });

        let pipeline = device.create_compute_pipeline(&wgpu::ComputePipelineDescriptor {
            label: Some("paraviz-mc-compute-pipeline"),
            layout: Some(&pipeline_layout),
            module: &shader,
            entry_point: Some("mc_main"),
            compilation_options: Default::default(),
            cache: None,
        });

        let edge_table_buf = device.create_buffer_init(&wgpu::util::BufferInitDescriptor {
            label: Some("paraviz-mc-edge-table"),
            contents: bytemuck::cast_slice(&EDGE_TABLE),
            usage: wgpu::BufferUsages::STORAGE,
        });

        let tri_table_flat: Vec<i32> = TRI_TABLE.iter().flatten().copied().collect();
        let tri_table_buf = device.create_buffer_init(&wgpu::util::BufferInitDescriptor {
            label: Some("paraviz-mc-tri-table"),
            contents: bytemuck::cast_slice(&tri_table_flat),
            usage: wgpu::BufferUsages::STORAGE,
        });

        Self {
            device,
            queue,
            bgl,
            pipeline,
            edge_table_buf,
            tri_table_buf,
        }
    }

    /// Extracts an isosurface at `iso_value` from `image` (`field_name` or active scalars if empty)
    /// using the GPU Marching Cubes compute shader, returning a welded watertight [`PolyData`]
    /// with smooth normals and interpolated scalar values.
    pub fn contour_imagedata(
        &self,
        image: &ImageData,
        field_name: &str,
        iso_value: f64,
    ) -> Result<PolyData, RenderError> {
        let [nx, ny, nz] = image.dimensions;
        if nx < 2 || ny < 2 || nz < 2 {
            return Ok(PolyData::new());
        }

        let arr = if field_name.is_empty() {
            image.point_data.active_scalars_array()
        } else {
            image.point_data.get(field_name)
        };
        let Some(arr) = arr else {
            return Ok(PolyData::new());
        };
        let scalar_name = arr.name.clone();

        let expected_pts = nx * ny * nz;
        let mut scalars = arr.to_scalar_f32(None);
        if scalars.len() < expected_pts {
            scalars.resize(expected_pts, 0.0);
        } else if scalars.len() > expected_pts {
            scalars.truncate(expected_pts);
        }

        let scalar_buf = self.device.create_buffer_init(&wgpu::util::BufferInitDescriptor {
            label: Some("paraviz-mc-scalars"),
            contents: bytemuck::cast_slice(&scalars),
            usage: wgpu::BufferUsages::STORAGE,
        });

        let cx = (nx - 1) as u32;
        let cy = (ny - 1) as u32;
        let cz = (nz - 1) as u32;
        let total_cells = cx as usize * cy as usize * cz as usize;
        // Cap initial allocation safely inside WebGPU's 128 MiB storage buffer limit.
        let initial_cap = (total_cells * 5).clamp(64, 600_000) as u32;

        let (tri_count, raw_verts) =
            self.dispatch_and_readback(image, &scalar_buf, iso_value as f32, cx, cy, cz, initial_cap)?;

        let raw_verts = if tri_count > initial_cap {
            let max_supported = (self.device.limits().max_storage_buffer_binding_size as usize)
                / (3 * std::mem::size_of::<GpuMcVertex>());
            let retry_cap = (tri_count as usize).min(max_supported) as u32;
            let (_, verts) = self.dispatch_and_readback(
                image,
                &scalar_buf,
                iso_value as f32,
                cx,
                cy,
                cz,
                retry_cap,
            )?;
            verts
        } else {
            raw_verts
        };

        if raw_verts.is_empty() {
            return Ok(PolyData::new());
        }

        // Weld vertices by canonical grid edge key so the output PolyData is a closed 2-manifold.
        let mut edge_to_vid: HashMap<u64, u32> = HashMap::with_capacity(raw_verts.len());
        let mut points: Vec<[f32; 3]> = Vec::with_capacity(raw_verts.len() / 2);
        let mut normals: Vec<[f32; 3]> = Vec::with_capacity(raw_verts.len() / 2);
        let mut out_scalars: Vec<f32> = Vec::with_capacity(raw_verts.len() / 2);
        let mut tris: Vec<[u32; 3]> = Vec::with_capacity(raw_verts.len() / 3);

        for tri in raw_verts.as_chunks::<3>().0 {
            let mut idx = [0u32; 3];
            for (k, v) in tri.iter().enumerate() {
                let key = ((v.edge_key[0] as u64) << 32) | (v.edge_key[1] as u64);
                let vid = *edge_to_vid.entry(key).or_insert_with(|| {
                    let id = points.len() as u32;
                    points.push([v.pos_scalar[0], v.pos_scalar[1], v.pos_scalar[2]]);
                    normals.push([v.normal_t[0], v.normal_t[1], v.normal_t[2]]);
                    out_scalars.push(v.pos_scalar[3]);
                    id
                });
                idx[k] = vid;
            }
            if idx[0] != idx[1] && idx[1] != idx[2] && idx[2] != idx[0] {
                tris.push(idx);
            }
        }

        let mut poly = PolyData::from_triangles(points, tris);
        poly.point_data
            .set_scalars(DataArray::scalars_f32(scalar_name, out_scalars));
        poly.point_data
            .set_normals(DataArray::vectors_f32("Normals", normals));
        Ok(poly)
    }

    #[allow(clippy::too_many_arguments)]
    fn dispatch_and_readback(
        &self,
        image: &ImageData,
        scalar_buf: &wgpu::Buffer,
        iso_value: f32,
        cx: u32,
        cy: u32,
        cz: u32,
        max_triangles: u32,
    ) -> Result<(u32, Vec<GpuMcVertex>), RenderError> {
        let uniforms = McUniforms {
            dims: [
                image.dimensions[0] as u32,
                image.dimensions[1] as u32,
                image.dimensions[2] as u32,
                0,
            ],
            origin: [
                image.origin[0] as f32,
                image.origin[1] as f32,
                image.origin[2] as f32,
                0.0,
            ],
            spacing: [
                image.spacing[0] as f32,
                image.spacing[1] as f32,
                image.spacing[2] as f32,
                iso_value,
            ],
            max_triangles,
            _pad0: 0,
            _pad1: 0,
            _pad2: 0,
        };

        let uniform_buf = self.device.create_buffer_init(&wgpu::util::BufferInitDescriptor {
            label: Some("paraviz-mc-uniform"),
            contents: bytemuck::bytes_of(&uniforms),
            usage: wgpu::BufferUsages::UNIFORM,
        });

        let counter_buf = self.device.create_buffer_init(&wgpu::util::BufferInitDescriptor {
            label: Some("paraviz-mc-counter"),
            contents: bytemuck::bytes_of(&0u32),
            usage: wgpu::BufferUsages::STORAGE | wgpu::BufferUsages::COPY_SRC,
        });

        let out_size = (max_triangles as u64) * 3 * (std::mem::size_of::<GpuMcVertex>() as u64);
        let out_verts_buf = self.device.create_buffer(&wgpu::BufferDescriptor {
            label: Some("paraviz-mc-out-verts"),
            size: out_size,
            usage: wgpu::BufferUsages::STORAGE | wgpu::BufferUsages::COPY_SRC,
            mapped_at_creation: false,
        });

        let bind_group = self.device.create_bind_group(&wgpu::BindGroupDescriptor {
            label: Some("paraviz-mc-bg"),
            layout: &self.bgl,
            entries: &[
                wgpu::BindGroupEntry {
                    binding: 0,
                    resource: uniform_buf.as_entire_binding(),
                },
                wgpu::BindGroupEntry {
                    binding: 1,
                    resource: scalar_buf.as_entire_binding(),
                },
                wgpu::BindGroupEntry {
                    binding: 2,
                    resource: self.edge_table_buf.as_entire_binding(),
                },
                wgpu::BindGroupEntry {
                    binding: 3,
                    resource: self.tri_table_buf.as_entire_binding(),
                },
                wgpu::BindGroupEntry {
                    binding: 4,
                    resource: counter_buf.as_entire_binding(),
                },
                wgpu::BindGroupEntry {
                    binding: 5,
                    resource: out_verts_buf.as_entire_binding(),
                },
            ],
        });

        let counter_staging = self.device.create_buffer(&wgpu::BufferDescriptor {
            label: Some("paraviz-mc-counter-staging"),
            size: 4,
            usage: wgpu::BufferUsages::MAP_READ | wgpu::BufferUsages::COPY_DST,
            mapped_at_creation: false,
        });

        let mut encoder = self
            .device
            .create_command_encoder(&wgpu::CommandEncoderDescriptor {
                label: Some("paraviz-mc-encoder"),
            });
        {
            let mut cpass = encoder.begin_compute_pass(&wgpu::ComputePassDescriptor {
                label: Some("paraviz-mc-pass"),
                timestamp_writes: None,
            });
            cpass.set_pipeline(&self.pipeline);
            cpass.set_bind_group(0, &bind_group, &[]);
            cpass.dispatch_workgroups(cx.div_ceil(4), cy.div_ceil(4), cz.div_ceil(4));
        }
        encoder.copy_buffer_to_buffer(&counter_buf, 0, &counter_staging, 0, 4);
        self.queue.submit(Some(encoder.finish()));

        let tri_count = self.read_u32_buffer(&counter_staging)?;
        let actual_tris = tri_count.min(max_triangles);
        if actual_tris == 0 || tri_count > max_triangles {
            return Ok((tri_count, Vec::new()));
        }

        let read_bytes = (actual_tris as u64) * 3 * (std::mem::size_of::<GpuMcVertex>() as u64);
        let verts_staging = self.device.create_buffer(&wgpu::BufferDescriptor {
            label: Some("paraviz-mc-verts-staging"),
            size: read_bytes,
            usage: wgpu::BufferUsages::MAP_READ | wgpu::BufferUsages::COPY_DST,
            mapped_at_creation: false,
        });

        let mut copy_enc = self
            .device
            .create_command_encoder(&wgpu::CommandEncoderDescriptor {
                label: Some("paraviz-mc-readback-encoder"),
            });
        copy_enc.copy_buffer_to_buffer(&out_verts_buf, 0, &verts_staging, 0, read_bytes);
        self.queue.submit(Some(copy_enc.finish()));

        let verts = self.read_vertex_buffer(&verts_staging, actual_tris as usize * 3)?;
        Ok((tri_count, verts))
    }

    fn read_u32_buffer(&self, staging: &wgpu::Buffer) -> Result<u32, RenderError> {
        let slice = staging.slice(..);
        let (tx, rx) = std::sync::mpsc::channel();
        slice.map_async(wgpu::MapMode::Read, move |res| {
            let _ = tx.send(res);
        });
        self.device
            .poll(wgpu::PollType::wait_indefinitely())
            .map_err(|e| RenderError::DevicePoll(format!("{e:?}")))?;
        rx.recv()
            .map_err(|e| RenderError::BufferMap(e.to_string()))?
            .map_err(|e| RenderError::BufferMap(format!("{e:?}")))?;
        let mapped = slice
            .get_mapped_range()
            .map_err(|e| RenderError::BufferMap(format!("{e:?}")))?;
        let val = *bytemuck::from_bytes::<u32>(&mapped[..4]);
        drop(mapped);
        staging.unmap();
        Ok(val)
    }

    fn read_vertex_buffer(
        &self,
        staging: &wgpu::Buffer,
        count: usize,
    ) -> Result<Vec<GpuMcVertex>, RenderError> {
        let slice = staging.slice(..);
        let (tx, rx) = std::sync::mpsc::channel();
        slice.map_async(wgpu::MapMode::Read, move |res| {
            let _ = tx.send(res);
        });
        self.device
            .poll(wgpu::PollType::wait_indefinitely())
            .map_err(|e| RenderError::DevicePoll(format!("{e:?}")))?;
        rx.recv()
            .map_err(|e| RenderError::BufferMap(e.to_string()))?
            .map_err(|e| RenderError::BufferMap(format!("{e:?}")))?;
        let mapped = slice
            .get_mapped_range()
            .map_err(|e| RenderError::BufferMap(format!("{e:?}")))?;
        let verts: &[GpuMcVertex] = bytemuck::cast_slice(&mapped);
        let out = verts[..count].to_vec();
        drop(mapped);
        staging.unmap();
        Ok(out)
    }
}

